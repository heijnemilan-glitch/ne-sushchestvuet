  mainScreen(termId) {
    const mem = this.mem;
    const opts = [];
    const pending = this.operatorMessages().find((m) => !this.seenMsg(m.id) && m.cond());
    let body = '';
    if (termId === 'tv') return this.voidScreen();
    if (pending) {
      body = `ОПЕРАТОР:\n${this.glitch(pending.text)}`;
      mem.flag(`msg_${pending.id}`);
      mem.seeEvent('operator_msg');
      for (const o of pending.options) {
        opts.push({
          label: o.label,
          run: () => {
            if (o.trust) this.trust(o.trust, `${pending.id}_${o.label}`);
            mem.decide(pending.id, o.label);
            return { body: `ОПЕРАТОР:\n${this.glitch(o.reply)}`, options: [{ label: 'Далее', run: () => this.mainScreen(termId) }] };
          },
        });
      }
      return { body, options: opts };
    }
    body = `ОПЕРАТОР:\n${this.glitch(this.idleLine())}`;
    for (const f of this.files(termId)) opts.push({ label: f.label, run: () => ({ body: f.body(), options: [{ label: 'Назад', run: () => this.mainScreen(termId) }] }) });
    if (termId === 't5') opts.push(...this.coreOptions());
    opts.push({ label: 'Выйти', run: () => null });
    return { body, options: opts };
  }

