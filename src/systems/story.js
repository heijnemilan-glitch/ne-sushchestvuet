  voidScreen() {
    const mem = this.mem;
    const g = this.game;
    const frags = ['frag1', 'frag2', 'frag3'].filter((f) => g.inv.has(f)).length;
    const ready = frags === 3 && mem.get('observer_seen') >= 2 && mem.discoveredRules().length >= 5;
    const answer = (label, text) => ({
      label,
      run: () => ({ body: text, options: [{ label: 'Назад', run: () => this.voidScreen() }] }),
    });
    return {
      body: 'КТО ВЫ?',
      options: [
        answer('Испытуемый', 'ИСПЫТУЕМЫЙ НЕ ЗАРЕГИСТРИРОВАН НА ЭТОМ ЭТАЖЕ.\nНА ЭТОМ ЭТАЖЕ НИКТО НЕ ЗАРЕГИСТРИРОВАН.'),
        answer('Оператор', 'ОПЕРАТОР УЖЕ НА ЛИНИИ.\nОПЕРАТОР ВСЕГДА НА ЛИНИИ.\nВЫ НЕ ОПЕРАТОР. ПОКА.'),
        {
          label: 'Никто',
          run: () => {
            mem.decide('void_answer', 'никто');
            if (ready) {
              g.ending('ending_none');
              return null;
            }
            const missing = [];
            if (frags < 3) missing.push(`фрагментов плана: ${frags}/3`);
            if (mem.get('observer_seen') < 2) missing.push('свидетель не подтверждён');
            if (mem.discoveredRules().length < 5) missing.push('здание вас ещё не поняло');
            return {
              body: `НЕДОСТАТОЧНО ДАННЫХ.\nВы ещё существуете.\n\n(${missing.join('; ')})`,
              options: [{ label: 'Назад', run: () => this.voidScreen() }],
            };
          },
        },
        { label: 'Выйти', run: () => null },
      ],
    };
  }

